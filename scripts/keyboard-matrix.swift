// Checks every Draft keyboard shortcut against the US, German (QWERTZ), French (AZERTY) and Dvorak
// layouts and writes docs/INPUT_MATRIX.md. Reads the layouts' key maps from macOS without switching
// the current input source. Usage: swift scripts/keyboard-matrix.swift
import Carbon
import Foundation

let layouts = [("US", "com.apple.keylayout.US"), ("QWERTZ (German)", "com.apple.keylayout.German"),
               ("AZERTY (French)", "com.apple.keylayout.French"), ("Dvorak", "com.apple.keylayout.Dvorak")]

/// character → the modifiers needed to type it on this layout ("" plain, "⇧", "⌥", "⇧⌥").
func keyMap(_ id: String) -> [Character: String]? {
    let filter = [kTISPropertyInputSourceID as String: id] as CFDictionary
    guard let list = TISCreateInputSourceList(filter, true)?.takeRetainedValue() as? [TISInputSource], let src = list.first,
          let raw = TISGetInputSourceProperty(src, kTISPropertyUnicodeKeyLayoutData) else { return nil }
    let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
    var map: [Character: String] = [:]
    data.withUnsafeBytes { (buf: UnsafeRawBufferPointer) in
        let layout = buf.baseAddress!.assumingMemoryBound(to: UCKeyboardLayout.self)
        for (mods, label) in [(0, ""), (shiftKey >> 8, "⇧"), (optionKey >> 8, "⌥"), ((shiftKey | optionKey) >> 8, "⇧⌥")] {
            for code in 0..<128 {
                var dead: UInt32 = 0, len = 0
                var chars = [UniChar](repeating: 0, count: 4)
                UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), UInt32(mods), UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit), &dead, 4, &len, &chars)
                guard len == 1, let ch = String(utf16CodeUnits: chars, count: len).lowercased().first else { continue }
                if map[ch] == nil || (map[ch]!.count > label.count) { map[ch] = label }
            }
        }
    }
    return map
}

// Shortcuts from the source: SwiftUI menu shortcuts and editor commands.
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
var shortcuts: [(String, Character)] = []
for dir in ["Sources/Draft", "Sources/DraftEditor"] {
    for f in (FileManager.default.enumerator(atPath: root.appendingPathComponent(dir).path)?.allObjects as? [String] ?? []) where f.hasSuffix(".swift") && !f.hasPrefix("Automation") {
        let s = (try? String(contentsOf: root.appendingPathComponent(dir).appendingPathComponent(f), encoding: .utf8)) ?? ""
        let re = try! NSRegularExpression(pattern: #"keyboardShortcut\("(.)"(?:, modifiers: \[([^\]]*)\])?\)|shortcut: "([^"]+)", key: "(.)""#)
        for m in re.matches(in: s, range: NSRange(s.startIndex..., in: s)) {
            func g(_ i: Int) -> String? { Range(m.range(at: i), in: s).map { String(s[$0]) } }
            if let k = g(1) {
                let mods = (g(2) ?? ".command").replacingOccurrences(of: ".control", with: "⌃").replacingOccurrences(of: ".option", with: "⌥")
                    .replacingOccurrences(of: ".shift", with: "⇧").replacingOccurrences(of: ".command", with: "⌘").replacingOccurrences(of: ", ", with: "")
                shortcuts.append((mods + k.uppercased(), Character(k.lowercased())))
            } else if let disp = g(3), let k = g(4), k.count == 1 { shortcuts.append((disp, Character(k.lowercased()))) }
        }
    }
}
var seen = Set<String>()
shortcuts = shortcuts.filter { seen.insert($0.0).inserted }.sorted { $0.0 < $1.0 }
let maps = layouts.map { ($0.0, keyMap($0.1)) }
var md = ["# Keyboard layouts and input methods", "",
          "Generated by `swift scripts/keyboard-matrix.swift` from the layouts installed in macOS (the current input source is not changed).",
          "✓ = the key exists unshifted · ⇧ = needs Shift (the shortcut then also includes Shift) · ⌥ = only reachable with Option.", "",
          "macOS (12 and later) localizes menu shortcuts whose key needs Option on the current layout, so ⌥ entries still work from the menu; " +
          "the table shows where a person on that layout presses something different from the menu label.", "",
          "| Shortcut | " + layouts.map(\.0).joined(separator: " | ") + " |", "|---|" + String(repeating: "---|", count: layouts.count)]
var issues = 0
for (label, ch) in shortcuts where !["↑", "↓", "←", "→"].contains(ch) {
    let cells = maps.map { _, m -> String in
        guard let m else { return "layout missing" }
        guard let need = m[ch] else { issues += 1; return "⚠ not on this layout" }
        if need.contains("⌥") { issues += 1; return "⚠ \(need)" }
        return need.isEmpty ? "✓" : need
    }
    md.append("| \(label) | " + cells.joined(separator: " | ") + " |")
}
md += ["", "Arrow-key, Return, Tab and Escape shortcuts use key positions, not characters, and work the same on every layout.", "",
       "## Input methods (composition)", "",
       "Checked by `IMETests` (Japanese kana → kanji, Chinese pinyin with candidate changes, Korean in Spectrum text, slash and Markdown triggers, a bold heading):",
       "- Marked (composing) text never splits a block, never commits early and keeps the block id.",
       "- Slash commands, mentions and Markdown shortcuts wait for committed text.",
       "- Committed text takes the formatting and text effect around it; Spectrum drawing doesn't disturb composition.",
       "- Return and Enter during composition belong to the input method (they commit the candidate); AppKit doesn't send them to the editor.", "",
       "## Limits (need a person)", "",
       "- Typing with physical QWERTZ/AZERTY/Dvorak keyboards and the real Japanese (Kotoeri) and Chinese (Pinyin) input methods is not automated here.",
       "- Candidate-window placement next to the caret is drawn by macOS and was not checked."]
try! md.joined(separator: "\n").write(to: root.appendingPathComponent("docs/INPUT_MATRIX.md"), atomically: true, encoding: .utf8)
print("\(shortcuts.count) shortcuts × \(layouts.count) layouts, \(issues) cells need Option or are missing")
